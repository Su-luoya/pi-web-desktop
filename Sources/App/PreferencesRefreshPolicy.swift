import Foundation

/// 设置窗口刷新策略（outD-3）。
///
/// 设置窗口是单例，配置还有两条不经过它的写路径：菜单「复制手机访问链接」
/// 确认切换监听地址、以及工作目录切换。旧实现在窗口可见时完全不刷新控件，
/// 于是用户随后点“保存”会用打开窗口时的旧值重建配置并写回——刚在菜单里做的
/// 切换被静默回滚。
///
/// 直接把新值刷进控件也不行：那会抹掉用户正在输入、尚未保存的内容。因此刷新
/// 只在**没有被用户改动过**的窗口上执行。改动判定看控件值是否等于上次同步进
/// 控件的快照（`loadedValues`）：
///
/// - 全部相等 → 用户没动过任何字段，可以整体刷新；
/// - 有差异 → 保留用户输入，只把新配置记作基线（第一次编辑前的值），
///   不刷新控件。
///
/// 用户在外部改动之后继续编辑时，保存写回的仍是用户看到并确认过的值，
/// 不会出现“控件显示 A、写回 B”。
enum PreferencesRefreshPolicy {
    /// 是否可以把新配置刷进控件。
    ///
    /// - Parameters:
    ///   - currentValues: 控件当前值的快照。
    ///   - loadedValues: 上一次同步进控件的快照（用户未编辑时两者相等）。
    static func shouldReload(currentValues: [String], loadedValues: [String]) -> Bool {
        currentValues == loadedValues
    }
}
